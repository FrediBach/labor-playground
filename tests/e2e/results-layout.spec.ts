import { expect, test } from '@playwright/test'

test('results give the waveform room and expand without changing sidebar preferences or the circuit', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.getByLabel('Simulation status', { exact: true })).toHaveAttribute('data-state', 'ready')
  const saved = await page.evaluate(() => localStorage.getItem('labor-playground.document.v1'))
  await page.getByRole('tab', { name: 'Results', exact: true }).click()
  const scope = page.getByRole('region', { name: 'Oscilloscope', exact: true })
  const canvas = page.getByLabel('Voltage versus time for scope channels 1 and 2')
  expect((await canvas.boundingBox())!.height).toBeGreaterThanOrEqual(300)
  await expect(scope.getByRole('region', { name: 'Simulation recording', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Pico scope logs', exact: true })).toHaveCount(0)
  await page.getByLabel('Recording time milliseconds').fill('15')
  const before = (await canvas.boundingBox())!.width
  await page.getByRole('button', { name: 'Expand results workspace' }).click()
  await expect(page.getByRole('complementary', { name: 'Parts library' })).toBeHidden()
  expect((await canvas.boundingBox())!.width).toBeGreaterThan(before + 200)
  await expect(page.getByLabel('Recording time milliseconds')).toHaveValue('15')
  await page.screenshot({ path: testInfo.outputPath('results-desktop.png'), fullPage: true })
  await page.getByRole('tab', { name: 'Circuit', exact: true }).click()
  await expect(page.getByRole('complementary', { name: 'Parts library' })).toBeVisible()
  await page.getByRole('tab', { name: 'Results', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Expand results workspace' })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Expand results workspace' }).click()
  await expect(page.getByRole('complementary', { name: 'Parts library' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(canvas).toBeVisible()
  expect((await canvas.boundingBox())!.height).toBeGreaterThanOrEqual(250)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: testInfo.outputPath('results-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => localStorage.getItem('labor-playground.document.v1'))).toBe(saved)
  await expect(page.getByRole('button', { name: 'Undo', exact: true })).toBeDisabled()
  expect(errors).toEqual([])
})
