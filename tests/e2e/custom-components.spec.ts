test('distinct same-kind click/drag placement, lead edits, clear, recovery, export and fresh import', async ({ page, browser }) => {
  await page.goto('/')
  await library(page).getByRole('button', { name: 'Clear board', exact: true }).click()
  await create(page, 'Model A')
  await terminal(page, 'a5').click()
  await page.keyboard.press('Escape')
  await expect(page.locator('[data-part="R1"]')).toHaveAttribute('aria-label', /Model A/)
  await create(page, 'Model B')
  await library(page).getByRole('button', { name: 'Model B', exact: true }).dragTo(terminal(page, 'a15'))
  await page.keyboard.press('Escape')
  await expect.poll(async () => (await recovered(page)).parts.length).toBe(2)
  await page.locator('[data-part="R2"]').focus()
  await inspector(page).getByRole('button', { name: 'Move R2 lead 2', exact: true }).click()
  await terminal(page, 'a20').click()
  await expect.poll(async () => (await recovered(page)).parts[1].pins[1]).toBe('a20')
  const doc = await recovered(page)
  expect(doc.parts[0].customModelId).not.toBe(doc.parts[1].customModelId)
  await page.reload()
  await expect(library(page).getByRole('button', { name: 'Model A', exact: true })).toBeVisible()
  await expect(page.locator('[data-part="R2"]')).toHaveAttribute('aria-label', /Model B/)
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export circuit' }).click()
  const download = await downloadEvent
  const filePath = await download.path()
  const context = await browser.newContext()
  const fresh = await context.newPage(); await fresh.goto('/')
  await fresh.locator('input[type=file]').setInputFiles(filePath!)
  await expect.poll(async () => (await recovered(fresh))?.customComponents?.length).toBe(2)
  await expect(fresh.locator('[data-part="R1"]')).toHaveAttribute('aria-label', /Model A/)
  await context.close()
  await library(page).getByRole('button', { name: 'Clear board', exact: true }).click()
  await expect(page.locator('[data-part]')).toHaveCount(0)
  await expect(library(page).getByRole('button', { name: 'Model B', exact: true })).toBeVisible()
  await library(page).getByRole('button', { name: 'Delete Model B', exact: true }).click()
  await expect(library(page).getByRole('button', { name: 'Model B', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(library(page).getByRole('button', { name: 'Model B', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('[data-part]')).toHaveCount(2)
})

