test('nonlinear DC readings, stale edits, long names and example replacement undo', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('combobox', { name: 'Load example' }).selectOption('custom-resistance')
  await ready(page)
  await page.locator('[data-part="R1"]').focus()
  const pane = inspector(page)
  // Switch the source to DC using the portable document, preserving the same model.
  const doc = await recovered(page)
  doc.wires[0].from = 'cv'
  await page.locator('input[type=file]').setInputFiles({ name: 'custom-dc.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(doc)) })
  await ready(page)
  await page.locator('[data-part="R1"]').click()
  await expect(pane.getByLabel('DC current 1 → 2', { exact: true })).toHaveText(/2\.071 mA/)
  await page.getByRole('tab', { name: 'Results', exact: true }).click()
  await page.getByRole('checkbox', { name: 'Auto update', exact: true }).uncheck()
  await page.getByRole('tab', { name: 'Circuit', exact: true }).click()
  await pane.getByRole('button', { name: 'Edit model', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const name = 'A long custom resistor name '.repeat(3).slice(0, 80)
  await dialog.getByRole('textbox', { name: 'Model name' }).fill(name)
  await dialog.getByRole('spinbutton', { name: 'Row 1 value' }).fill('1.1')
  await dialog.getByRole('button', { name: 'Save model' }).click()
  await expect(page.getByRole('status', { name: 'Simulation status', exact: true })).toHaveAttribute('data-state', 'stale')
  await expect(pane.getByLabel('DC current 1 → 2', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(pane.getByRole('heading', { name: 'Current-sensitive resistor', exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: 'Load example' }).selectOption('rc-filter')
  await expect(library(page).getByRole('button', { name: 'Current-sensitive resistor', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(library(page).getByRole('button', { name: 'Current-sensitive resistor', exact: true })).toBeVisible()
})

test('storage failure preserves custom models in memory and export, and mobile editor fits', async ({ page }) => {
  await page.addInitScript(() => { Storage.prototype.setItem = () => { throw new DOMException('Full', 'QuotaExceededError') } })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await library(page).getByRole('button', { name: 'Create custom component' }).click()
  const dialog = page.getByRole('dialog')
  const bounds = await dialog.boundingBox()
  expect(bounds!.width).toBeLessThanOrEqual(390)
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  await dialog.getByRole('textbox', { name: 'Model name' }).fill('Survives storage failure')
  await page.screenshot({ path: '/tmp/labor-custom-editor-mobile.png' })
  await dialog.getByRole('button', { name: 'Save model' }).click()
  await expect(library(page).getByRole('button', { name: 'Survives storage failure', exact: true })).toBeVisible()
  const event = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export circuit' }).click()
  const stream = await (await event).createReadStream()
  const chunks: Buffer[] = []
  for await (const chunk of stream!) chunks.push(chunk)
  expect(JSON.parse(Buffer.concat(chunks).toString()).customComponents[0].name).toBe('Survives storage failure')
})
