  await expect.poll(async () => (await recovered(page)).customComponents.length).toBe(2)
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(inspector(page).getByRole('heading', { name: 'Current-sensitive resistor', exact: true })).toBeVisible()
  expect(errors).toEqual([])
