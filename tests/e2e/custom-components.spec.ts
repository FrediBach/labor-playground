  await dialog.getByRole('spinbutton', { name: 'Row 2 axis' }).fill('0')
  await expect(dialog.getByRole('button', { name: 'Save model' })).toBeDisabled()
  await expect(dialog.getByRole('alert')).toContainText('Row 2')
  await dialog.getByRole('spinbutton', { name: 'Row 2 axis' }).fill('10')
  await dialog.getByRole('spinbutton', { name: 'Row 2 value' }).fill('4')
  await dialog.getByRole('button', { name: 'Save model' }).click()
  await expect.poll(async () => (await recovered(page)).customComponents?.length).toBe(1)
  await page.locator('[data-part="R1"]').focus()
  await inspector(page).getByRole('combobox', { name: 'Component model' }).selectOption({ label: 'Current-sensitive resistor' })
  await expect(inspector(page).getByRole('spinbutton', { name: 'Resistance', exact: true })).toHaveCount(0)
  await ready(page)
  await inspector(page).getByRole('button', { name: 'Edit model', exact: true }).click()
  await expect(dialog).toContainText('Saving updates 1 placed instance')
  await dialog.getByRole('spinbutton', { name: 'Row 1 value' }).fill('2')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
