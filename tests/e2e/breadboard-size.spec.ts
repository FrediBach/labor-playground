test('dragging between added rows and moving a lead each make one undoable edit', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 2200 })
  await page.goto('/')
  await page.getByRole('button', { name: 'Clear board', exact: true }).click()
  await columns(page).selectOption('60')
  await rows(page).selectOption('3')
  await page.getByRole('button', { name: 'Fit workbench', exact: true }).click()
  await page.getByRole('complementary', { name: 'Parts library' }).getByRole('button', { name: /Resistor/ }).click()
  await terminal(page, 'r2:a40').click()
  await page.getByRole('button', { name: 'Select tool', exact: true }).click()
  const part = page.locator('[data-part="R1"]')
  const drag = await part.evaluate(element => {
    const matrix = element.closest('svg')!.getScreenCTM()!
    const origin = new DOMPoint(100 + 40.5 * 24, 170 + 480).matrixTransform(matrix)
    const destination = new DOMPoint(100 + 40.5 * 24, 170 + 960).matrixTransform(matrix)
    return { x: origin.x, y: origin.y, toX: destination.x, toY: destination.y }
  })
  await page.mouse.move(drag.x, drag.y)
  await page.mouse.down()
  await page.mouse.move(drag.toX, drag.toY, { steps: 10 })
  await page.mouse.up()
  await expect.poll(async () => (await recovered(page)).parts[0]?.pins).toEqual(['r3:a40', 'r3:a43'])
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect.poll(async () => (await recovered(page)).parts[0]?.pins).toEqual(['r2:a40', 'r2:a43'])
  await page.getByRole('button', { name: 'Redo', exact: true }).click()
  await part.focus()
  await page.getByRole('complementary', { name: 'Inspector' }).getByRole('button', { name: 'Move R1 lead 2', exact: true }).click()
  await terminal(page, 'r3:a44').click()
  await expect.poll(async () => (await recovered(page)).parts[0]?.pins).toEqual(['r3:a40', 'r3:a44'])
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect.poll(async () => (await recovered(page)).parts[0]?.pins).toEqual(['r3:a40', 'r3:a43'])
})


for (const screen of [{ width: 1440, height: 1120 }, { width: 700, height: 900 }]) {
  test(`adding rows grows the board area without shrinking holes at ${screen.width}px`, async ({ page }) => {
    await page.setViewportSize(screen)
    await page.goto('/')
    const viewport = page.getByTestId('board-viewport')
    const geometry = () => viewport.evaluate(element => ({
      height: element.clientHeight,
      scale: element.querySelector('svg')!.getScreenCTM()!.a,
      zoom: element.getAttribute('data-zoom'),
    }))
    for (const width of ['30', '60']) {
      await rows(page).selectOption('1')
      await columns(page).selectOption(width)
      await page.getByRole('button', { name: 'Zoom in', exact: true }).click()
      const original = await geometry()
      for (const count of ['2', '3']) {
        await rows(page).selectOption(count)
        await expect.poll(async () => (await geometry()).height).toBeGreaterThan(original.height * Number(count) * 0.85)
        await expect.poll(async () => Math.abs((await geometry()).scale - original.scale)).toBeLessThan(0.002)
        expect((await geometry()).zoom).toBe(original.zoom)
      }
      await page.getByRole('button', { name: 'Undo', exact: true }).click()
      await expect(rows(page)).toHaveValue('2')
      await rows(page).selectOption('1')
      await expect.poll(async () => Math.abs((await geometry()).height - original.height)).toBeLessThanOrEqual(1)
    }
  })
}
